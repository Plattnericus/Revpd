// The wizard strings live in their own file so the first-run texts can be read
// side by side across languages. Merged in here so callers see one dictionary.
const base = { de, en, fr, es, it, nl, pl, pt, tr, ru }
const setup = {
  de: setupDe,
  en: setupEn,
  fr: setupFr,
  es: setupEs,
  it: setupIt,
  nl: setupNl,
  pl: setupPl,
  pt: setupPt,
  tr: setupTr,
  ru: setupRu,
}

export const dictionaries = Object.fromEntries(
  (Object.keys(base) as Lang[]).map((l) => [l, { ...base[l], ...setup[l] }]),
) as Record<Lang, Dict & Record<SetupKey, string>>

/** Picks the best match for the browser's preference, falling back to English. */
export function detectLang(): Lang {
  const saved = localStorage.getItem('revpd.lang')
  if (saved && saved in dictionaries) return saved as Lang

  for (const pref of navigator.languages ?? [navigator.language]) {
    const base = pref.toLowerCase().split('-')[0]
    if (base && base in dictionaries) return base as Lang
  }
  return 'en'
}
