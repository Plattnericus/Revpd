/**
 * settingHint explains one setting.
 *
 * Returns an empty string when nothing is written for the key, which is the
 * signal to fall back to the hint the server sent with the setting — several
 * have none at all, and their fields say enough on their own.
 */
export function settingHint(lang: Lang, key: string): string {
  return hints[lang]?.[key] ?? en[key] ?? ''
}

