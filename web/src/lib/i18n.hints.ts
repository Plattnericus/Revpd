/*
  The line under each setting that says what it does and what it costs.

  Separate from the names in i18n.settings.ts only for length — the two follow
  the same rule. The server sends an English hint with every setting, and that
  stays the fallback: a setting added to the registry before anybody translates
  it still explains itself, in English, rather than going silent.

  These are not descriptions of the field. They say the thing somebody would
  otherwise find out the hard way — which is why several of them are about what
  happens when the value is wrong.
*/

